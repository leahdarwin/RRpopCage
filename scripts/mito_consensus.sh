#!/bin/bash

# ============================================================================
# Script: Mitochondrial consensus, alignment, and amino acid differences
#
# Description:
#   Slurm batch script that builds a majority-base mitochondrial consensus
#   sequence from each pool-seq BAM (samtools consensus; positions with depth
#   below min_depth become N), adds the D. melanogaster reference mtDNA
#   (BDGP6.32) and extra mtDNA reference sequences (SRR1663530, SRR1663606,
#   D. yakuba NC_001322.1), aligns everything with MAFFT, then calls
#   mito_translate.R to translate each CDS (Drosophila mitochondrial code) and
#   build amino acid difference tables.
#
# Usage:
#   sbatch scripts/mito_consensus.sh [extra_mito_fasta ...]
#   Optional extra FASTAs (e.g. another mito genome, one sequence each) are added
#   to the MSA and translated using the BDGP6.32 GTF coordinates mapped
#   through the alignment. Run from the project root (RRpopCage/).
#
# Author: Leah Darwin
# ============================================================================

#SBATCH -p batch
#SBATCH -N 1
#SBATCH -n 4
#SBATCH --mem=8G
#SBATCH -t 12:00:00
#SBATCH -o %j.out
#SBATCH -e %j.err

set -euo pipefail

##cluster specific module loads
module load samtools   # needs samtools >= 1.16 for `samtools consensus`
module load mafft
module load r/4.5.1-iikl

##sorted BAMs of the pool-seq reads aligned to BDGP6.32 (*.sorted.bam); these are too large to upload to github and will need to be regenerated by aligning the raw reads to the reference genome
bam_dir="aligned_reads_6.32"

##D. melanogaster BDGP6.32 reference genome fasta and Ensembl release 104 GTF; too large to upload to github, download and update these paths
ref_dir="ref_genome"
ref="${ref_dir}/Drosophila_melanogaster.BDGP6.32.dna.toplevel.fa"
gtf="${ref_dir}/Drosophila_melanogaster.BDGP6.32.104.gtf"
chrom="mitochondrion_genome"
min_depth=10

out_dir="output/mito"
cons_dir="${out_dir}/consensus"
mkdir -p "$cons_dir"

samtools --version | head -1

# Reference mito sequence (BDGP6.32), named "ref_BDGP6.32"
samtools faidx "$ref" "$chrom" | sed '1s/.*/>ref_BDGP6.32/' > "${out_dir}/ref_mito.fa"

# Per-sample consensus (majority base; positions with depth < min_depth become N)
for bam in "${bam_dir}"/*.sorted.bam; do
    sample=$(basename "$bam" .fq.gz.sorted.bam)
    [ -f "${bam}.bai" ] || samtools index "$bam"
    samtools consensus -a -d "$min_depth" -r "$chrom" -f fasta "$bam" \
        | sed "1s/.*/>${sample}/" > "${cons_dir}/${sample}.fa"
done

# Concatenate: reference first, then any extra references, then samples
all_fa="${out_dir}/mito_all_unaligned.fa"
cat "${out_dir}/ref_mito.fa" > "$all_fa"

# Extra reference sequences, renamed to clean, unique IDs
##small mtDNA fasta files are included in the data directory
fasta_db="data"
sed '1s/.*/>SRR1663530_mito/' "${fasta_db}/SRR1663530_mito.fa" >> "$all_fa"
sed '1s/.*/>SRR1663606_mito/' "${fasta_db}/SRR1663606_mito.fa" >> "$all_fa"
sed '1s/.*/>D_yakuba_NC_001322.1/' "${fasta_db}/Drosophila_yakuba_mitochondrion.fa" >> "$all_fa"
for extra in "$@"; do cat "$extra" >> "$all_fa"; done
cat "${cons_dir}"/*.fa >> "$all_fa"

# Multiple sequence alignment
msa="${out_dir}/mito_aligned.fa"
mafft --auto --thread 4 "$all_fa" > "$msa"

# Translate CDS (Drosophila mito code) and build AA difference matrices
Rscript scripts/mito_translate.R "$msa" "$gtf" "$chrom" "ref_BDGP6.32" "${out_dir}"
